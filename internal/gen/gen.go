// typeExpr is t as Go source, a def package's type by its alias.
func (g *gen) typeExpr(t reflect.Type) (string, error) {
	switch t.Kind() {
	case reflect.Pointer:
		e, err := g.typeExpr(t.Elem())
		return "*" + e, err
	case reflect.Slice:
		e, err := g.typeExpr(t.Elem())
		return "[]" + e, err
	case reflect.Struct:
		if t.Name() == "" && t.NumField() == 0 {
			return "struct{}", nil
		}
	default:
	}
	if t.PkgPath() == "" {
		return t.String(), nil
	}
	alias, ok := aliasOf(t.PkgPath())
	if !ok {
		return "", fmt.Errorf("type %s of a package the generator does not import", t)
	}
	g.imports[t.PkgPath()] = alias
	return alias + "." + t.Name(), nil
}

func isInteger(k reflect.Kind) bool {
	switch k {
	case reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return true
	default:
		return false
	}
}

// literal is the YAML value v as a Go value of type t: a structure from a
// mapping by field name, a list from a sequence, a pointer by new, an
// enum or bitmap constant from its name.
func (g *gen) literal(t reflect.Type, v any) (string, error) {
	switch t.Kind() {
	case reflect.Pointer:
		inner, err := g.literal(t.Elem(), v)
		if err != nil {
			return "", err
		}
		if t.Elem().Kind() == reflect.Struct {
			return "&" + inner, nil
		}
		return "new(" + inner + ")", nil
	case reflect.Struct:
		m, ok := v.(map[string]any)
		if !ok {
			return "", fmt.Errorf("%s from %T", t, v)
		}
		te, err := g.typeExpr(t)
		if err != nil {
			return "", err
		}
		var parts []string
		for i := range t.NumField() {
			f := t.Field(i)
			x, ok := m[f.Name]
			if !ok {
				continue
			}
			lit, err := g.literal(f.Type, x)
			if err != nil {
				return "", fmt.Errorf("%s.%s: %w", t.Name(), f.Name, err)
			}
			parts = append(parts, f.Name+": "+lit)
		}
		if len(parts) != len(m) {
			return "", fmt.Errorf("%s: a key names no field", t)
		}
		return te + "{" + strings.Join(parts, ", ") + "}", nil
	case reflect.Slice:
		l, ok := v.([]any)
		if !ok {
			return "", fmt.Errorf("%s from %T", t, v)
		}
		te, err := g.typeExpr(t)
		if err != nil {
			return "", err
		}
		var parts []string
		for _, x := range l {
			lit, err := g.literal(t.Elem(), x)
			if err != nil {
				return "", err
			}
			parts = append(parts, lit)
		}
		return te + "{" + strings.Join(parts, ", ") + "}", nil
	case reflect.Bool:
		b, ok := v.(bool)
		if !ok {
			return "", fmt.Errorf("bool from %T", v)
		}
		return strconv.FormatBool(b), nil
	case reflect.String:
		s, ok := v.(string)
		if !ok {
			return "", fmt.Errorf("string from %T", v)
		}
		return strconv.Quote(s), nil
	default:
	}
	te, err := g.typeExpr(t)
	if err != nil {
		return "", err
	}
	switch x := v.(type) {
	case string:
		if t.PkgPath() == "" {
			return "", fmt.Errorf("%s from the name %q", t, x)
		}
		alias, _ := aliasOf(t.PkgPath())
		return alias + "." + x, nil
	case int:
		return te + "(" + strconv.Itoa(x) + ")", nil
	case float64:
		if isInteger(t.Kind()) && x != float64(int64(x)) {
			return "", fmt.Errorf("%s from %v", t, x)
		}
		return te + "(" + float(x) + ")", nil
	}
	return "", fmt.Errorf("%s from %T", t, v)
}

// field returns the type of a Patch field ("A" or "A.B") and of the
// state field it shadows.
func field(d def, name string) (patch, state reflect.Type, sub string, err error) {
	top, sub, _ := strings.Cut(name, ".")
	pf, ok := d.patch.FieldByName(top)
	if !ok || top == "Null" {
		return nil, nil, "", fmt.Errorf("attribute %q: %s has none", top, d.name)
	}
	sf, ok := d.state.FieldByName(top)
	if !ok {
		return nil, nil, "", fmt.Errorf("attribute %q: %s state has none", top, d.name)
	}
	return pf.Type, sf.Type, sub, nil
}

func (g *gen) cluster(w *bytes.Buffer, c *rowfile.Cluster, d def) error {
	alias := g.use(d)
	fmt.Fprintf(w, "{\nName: %q, ID: %s.ClusterID,\n", d.name, alias)
	if len(c.Features) > 0 {
		w.WriteString("Features: []Feature{")
		for _, f := range c.Features {
			fmt.Fprintf(w, "{Name: %q, When: %s}, ", f.Name, whenp(f.When))
		}
		w.WriteString("},\n")
	}
	if err := g.attrs(w, "Attributes", c.Attributes); err != nil {
		return err
	}
	if err := g.attrs(w, "Initial", c.Initial); err != nil {
		return err
	}
	if err := g.commands(w, c, d); err != nil {
		return err
	}
	if err := g.declare(w, c, d); err != nil {
		return err
	}
	if c.Options != nil {
		fmt.Fprintf(w, "Options: &OptionList{List: %q, Current: %q, Method: %q},\n", c.Options.List, c.Options.Current, c.Options.Method)
	}
	if len(c.Attributes) > 0 || c.Options != nil {
		if err := g.apply(w, c, d); err != nil {
			return err
		}
	}
	if slices.ContainsFunc(c.Commands, func(cmd rowfile.Command) bool { return len(cmd.Change) > 0 }) {
		if err := g.watch(w, c, d); err != nil {
			return err
		}
	}
	if len(c.Events) > 0 {
		if err := g.events(w, c, d); err != nil {
			return err
		}
	}
	w.WriteString("},\n")
	return nil
}

// events emits the cluster's events and the fire closure that emits them
// through the typed server's Emit<Event>.
func (g *gen) events(w *bytes.Buffer, c *rowfile.Cluster, d def) error {
	var body bytes.Buffer
	w.WriteString("Events: []Event{\n")
	for i := range c.Events {
		e := &c.Events[i]
		names := make([]string, 0, len(e.Emit))
		fmt.Fprintf(&body, "case %d:\n", i)
		for _, x := range e.Emit {
			m, ok := d.server.MethodByName("Emit" + x.Event)
			if !ok || m.Type.NumIn() != 3 || m.Type.NumOut() != 1 {
				return fmt.Errorf("event %q: %s has none", x.Event, d.name)
			}
			lit := map[string]any{}
			for k, v := range x.Literal {
				lit[k] = v
			}
			data, err := g.literal(m.Type.In(2), lit)
			if err != nil {
				return fmt.Errorf("event %s: %w", x.Event, err)
			}
			fmt.Fprintf(&body, "if err := s.Emit%s(endpoint, %s); err != nil {\nreturn err\n}\n", x.Event, data)
			names = append(names, x.Event)
		}
		fmt.Fprintf(w, "{On: %q, Emit: %s},\n", e.On, strs(names))
	}
	w.WriteString("},\n")
	fmt.Fprintf(w, "fire: func(b *binding, ei int, endpoint uint16) error {\ns := %s.Wrap(b.server(%s.ClusterID))\nswitch ei {\n%s}\nreturn nil\n},\n",
		d.alias, d.alias, body.String())
	return nil
}

func (g *gen) attrs(w *bytes.Buffer, name string, as []rowfile.Attr) error {
	if len(as) == 0 {
		return nil
	}
	fmt.Fprintf(w, "%s: []Attr{\n", name)
	for i := range as {
		a := &as[i]
		fmt.Fprintf(w, "{Name: %q, Value: %s", a.Attribute, g.value(&a.Value, nil))
		if a.When != nil {
			fmt.Fprintf(w, ", When: %s", whenp(a.When))
		}
		if len(a.StateIn) > 0 {
			fmt.Fprintf(w, ", StateIn: %s", strs(a.StateIn))
		}
		w.WriteString("},\n")
	}
	w.WriteString("},\n")
	return nil
}

// commandField returns the type of a command's source field: the
// handler's request field, or the cluster's state field.
func commandField(d def, cmd *rowfile.Command, name string) (reflect.Type, error) {
	src := d.state
	if cmd.Handle != "" {
		h, ok := d.declare.FieldByName("Handle" + cmd.Handle)
		if !ok {
			return nil, fmt.Errorf("command %q: %s has no handler for it", cmd.Handle, d.name)
		}
		src = h.Type.In(1)
	}
	f, ok := src.FieldByName(name)
	if !ok {
		return nil, fmt.Errorf("field %q: %s has none", name, src)
	}
	return f.Type, nil
}

func cmdValues(cmd *rowfile.Command) []*rowfile.Value {
	if cmd.Raw != nil {
		return []*rowfile.Value{cmd.Raw}
	}
	out := make([]*rowfile.Value, 0, len(cmd.JSON))
	for _, k := range slices.Sorted(mapKeys(cmd.JSON)) {
		v := cmd.JSON[k]
		out = append(out, &v)
	}
	return out
}

// enumExpr is the integer key of an enum constant (or a bool) a command
// value maps.
func enumExpr(alias string) func(string) string {
	return func(k string) string {
		switch k {
		case "true":
			return "1"
		case "false":
			return "0"
		}
		return "int64(" + alias + "." + k + ")"
	}
}

func (g *gen) commands(w *bytes.Buffer, c *rowfile.Cluster, d def) error {
	if len(c.Commands) == 0 {
		return nil
	}
	alias := d.alias
	w.WriteString("Commands: []Command{\n")
	for i := range c.Commands {
		cmd := &c.Commands[i]
		kind, on := "change", cmd.Change
		switch {
		case cmd.Handle != "":
			kind, on = "handle", []string{cmd.Handle}
		case len(cmd.Write) > 0:
			kind, on = "write", cmd.Write
		}
		for _, v := range cmdValues(cmd) {
			if v.Field == "" {
				continue
			}
			if _, err := commandField(d, cmd, v.Field); err != nil {
				return err
			}
		}
		fmt.Fprintf(w, "{Kind: %q, On: %s", kind, strs(on))
		if cmd.Method != "" {
			fmt.Fprintf(w, ", Method: %q", cmd.Method)
		}
		if cmd.Raw != nil {
			fmt.Fprintf(w, ", Raw: &%s", g.value(cmd.Raw, enumExpr(alias)))
		} else if len(cmd.JSON) > 0 {
			w.WriteString(", JSON: []Field{")
			for _, k := range slices.Sorted(mapKeys(cmd.JSON)) {
				v := cmd.JSON[k]
				fmt.Fprintf(w, "{Key: %q, Value: %s}, ", k, g.value(&v, enumExpr(alias)))
			}
			w.WriteString("}")
		}
		if cmd.When != nil {
			fmt.Fprintf(w, ", When: %s", whenp(cmd.When))
		}
		if cmd.Derive != "" {
			fmt.Fprintf(w, ", Derive: %q", cmd.Derive)
		}
		w.WriteString("},\n")
	}
	w.WriteString("},\n")
	return nil
}

// assign emits the assignment of an attribute mapping's value to dst
// (d.Initial or p): a typed switch for an enum, a converted number
// otherwise, null for a value that is no number where the attribute is
// nullable. n counts the assignments when set.
func (g *gen) assign(w *bytes.Buffer, d def, a *rowfile.Attr, dst, st, ci string, ai int, count bool) error {
	if a.When == nil {
		return g.assignValue(w, d, a, dst, st, ci, ai, count)
	}
	fmt.Fprintf(w, "if b.match(%s) {\n", whenp(a.When))
	if err := g.assignValue(w, d, a, dst, st, ci, ai, count); err != nil {
		return err
	}
	w.WriteString("}\n")
	return nil
}

func (g *gen) assignValue(w *bytes.Buffer, d def, a *rowfile.Attr, dst, st, ci string, ai int, count bool) error {
	pt, stt, sub, err := field(d, a.Attribute)
	if err != nil {
		return err
	}
	if pt.Kind() != reflect.Pointer {
		return fmt.Errorf("attribute %s: patch field %s is no pointer", a.Attribute, pt)
	}
	top, _, _ := strings.Cut(a.Attribute, ".")
	target := pt.Elem()
	inc := ""
	if count {
		inc = "\nn++"
	}
	wrap := func(expr string) (string, error) { return "new(" + expr + ")", nil }
	if sub != "" {
		if target.Kind() != reflect.Struct {
			return fmt.Errorf("attribute %s: %s is no structure", a.Attribute, target)
		}
		sf, ok := target.FieldByName(sub)
		if !ok {
			return fmt.Errorf("attribute %s: %s has no field %s", a.Attribute, target, sub)
		}
		te, err := g.typeExpr(target)
		if err != nil {
			return err
		}
		target = sf.Type
		wrap = func(expr string) (string, error) { return "&" + te + "{" + sub + ": " + expr + "}", nil }
	}
	if a.Const != nil && len(a.Enum) == 0 {
		lit, err := g.literal(target, a.Const)
		if err != nil {
			return fmt.Errorf("attribute %s: %w", a.Attribute, err)
		}
		expr, _ := wrap(lit)
		fmt.Fprintf(w, "%s.%s = %s%s\n", dst, top, expr, inc)
		return nil
	}
	if len(a.Enum) > 0 {
		fmt.Fprintf(w, "switch b.text(%s, %s, %d) {\n", st, ci, ai)
		keys := slices.Sorted(mapKeys(a.Enum))
		for _, k := range keys {
			lit, err := g.literal(target, a.Enum[k])
			if err != nil {
				return fmt.Errorf("attribute %s: enum %s: %w", a.Attribute, k, err)
			}
			expr, _ := wrap(lit)
			fmt.Fprintf(w, "case %q:\n%s.%s = %s%s\n", strings.ToLower(k), dst, top, expr, inc)
		}
		w.WriteString("}\n")
		return nil
	}
	var conv string
	switch {
	case isInteger(target.Kind()):
		te, err := g.typeExpr(target)
		if err != nil {
			return err
		}
		conv = "conv[" + te + "](v)"
	case target.Kind() == reflect.Float32 || target.Kind() == reflect.Float64:
		te, err := g.typeExpr(target)
		if err != nil {
			return err
		}
		conv = te + "(v)"
	default:
		return fmt.Errorf("attribute %s: a number cannot become %s; map it with enum", a.Attribute, target)
	}
	expr, _ := wrap(conv)
	fmt.Fprintf(w, "if v, ok := b.number(%s, %s, %d); ok {\n%s.%s = %s%s\n}", st, ci, ai, dst, top, expr, inc)
	if stt.Kind() == reflect.Pointer {
		fmt.Fprintf(w, " else if b.null(%s, %s, %d) {\n%s.Null = append(%s.Null, %s.Attr%s)%s\n}", st, ci, ai, dst, dst, d.alias, top, inc)
	}
	w.WriteString("\n")
	return nil
}

func (g *gen) declare(w *bytes.Buffer, c *rowfile.Cluster, d def) error {
	alias := d.alias
	var body bytes.Buffer
	if len(c.Features) > 0 {
		if _, ok := d.declare.FieldByName("Features"); !ok {
			return fmt.Errorf("features: %s takes no feature selection", d.name)
		}
	}
	for _, f := range c.Features {
		if f.When == nil {
			fmt.Fprintf(&body, "d.Features |= %s.Feature%s\n", alias, f.Name)
			continue
		}
		fmt.Fprintf(&body, "if b.match(%s) {\nd.Features |= %s.Feature%s\n}\n", whenp(f.When), alias, f.Name)
	}
	for i := range c.Initial {
		a := &c.Initial[i]
		if a.Literal != nil {
			pt, _, _, err := field(d, a.Attribute)
			if err != nil {
				return err
			}
			lit, err := g.literal(pt, a.Literal)
			if err != nil {
				return fmt.Errorf("initial %s: %w", a.Attribute, err)
			}
			fmt.Fprintf(&body, "d.Initial.%s = %s\n", a.Attribute, lit)
			continue
		}
		if err := g.assign(&body, d, a, "d.Initial", "nil", "ci", i, false); err != nil {
			return fmt.Errorf("initial: %w", err)
		}
	}
	for _, n := range c.StartNull {
		if _, _, _, err := field(d, n); err != nil {
			return err
		}
		fmt.Fprintf(&body, "d.Initial.Null = append(d.Initial.Null, %s.Attr%s)\n", alias, n)
	}
	if err := g.handlers(&body, c, d); err != nil {
		return err
	}
	if err := g.onWrite(&body, c, d); err != nil {
		return err
	}
	if c.Options != nil {
		m, ok := materializers[d.name]
		if !ok {
			return fmt.Errorf("options: %s has no materializer", d.name)
		}
		fmt.Fprintf(&body, "b.options%s(&d, ci)\n", m)
	}
	if c.Ports == rowfile.PortsHost {
		m, ok := portMaterializers[d.name]
		if !ok {
			return fmt.Errorf("ports: %s has no port materializer", d.name)
		}
		fmt.Fprintf(&body, "if !b.ports%s(&d) {\nb.unserved(ci)\n}\n", m)
	}
	fmt.Fprintf(w, "declare: func(b *binding, ci int) device.Declaration {\nvar d %s.Declare\n%sreturn d\n},\n", alias, body.String())
	return nil
}

// fields is the accessor of the command fields the entries read, from
// src (the request or the state).
func fieldsFn(d def, cmds []*rowfile.Command, src string) (string, error) {
	names := map[string]bool{}
	for _, cmd := range cmds {
		for _, n := range rowfile.Derives[cmd.Derive] {
			if _, err := commandField(d, cmd, n); err != nil {
				return "", err
			}
			names[n] = true
		}
		for _, v := range cmdValues(cmd) {
			if v.Field != "" {
				if _, err := commandField(d, cmd, v.Field); err != nil {
					return "", err
				}
				names[v.Field] = true
			}
		}
	}
	if len(names) == 0 {
		return "func(string) (any, bool) { return nil, false }", nil
	}
	var b strings.Builder
	b.WriteString("func(name string) (any, bool) {\nswitch name {\n")
	for _, n := range slices.Sorted(mapKeys(names)) {
		fmt.Fprintf(&b, "case %q:\nreturn %s.%s, true\n", n, src, n)
	}
	b.WriteString("}\nreturn nil, false\n}")
	return b.String(), nil
}

// cond is the Go condition of a command's if on src.
func (g *gen) cond(d def, cmd *rowfile.Command, src string) (string, error) {
	if cmd.If == nil {
		return "true", nil
	}
	t, err := commandField(d, cmd, cmd.If.Field)
	if err != nil {
		return "", err
	}
	ref := src + "." + cmd.If.Field
	nilCheck := ""
	if t.Kind() == reflect.Pointer {
		nilCheck = ref + " != nil && "
		ref = "*" + ref
		t = t.Elem()
	}
	te, err := g.typeExpr(t)
	if err != nil {
		return "", err
	}
	consts, neg := cmd.If.In, ""
	if len(cmd.If.NotIn) > 0 {
		consts, neg = cmd.If.NotIn, "!"
	}
	var vals []string
	for _, x := range consts {
		switch {
		case t.Kind() == reflect.Bool && (x == "true" || x == "false"):
			vals = append(vals, x)
		case isInteger(t.Kind()) && x != "" && strings.Trim(x, "0123456789") == "":
			vals = append(vals, te+"("+x+")")
		case t.PkgPath() != "":
			vals = append(vals, d.alias+"."+x)
		default:
			return "", fmt.Errorf("if %s: %s from %q", cmd.If.Field, t, x)
		}
	}
	g.useStd("slices")
	return fmt.Sprintf("%s%sslices.Contains([]%s{%s}, %s)", nilCheck, neg, te, strings.Join(vals, ", "), ref), nil
}

func (g *gen) handlers(w *bytes.Buffer, c *rowfile.Cluster, d def) error {
	byName := map[string][]int{}
	var order []string
	for i := range c.Commands {
		h := c.Commands[i].Handle
		if h == "" {
			continue
		}
		if _, seen := byName[h]; !seen {
			order = append(order, h)
		}
		byName[h] = append(byName[h], i)
	}
	for _, h := range order {
		f, ok := d.declare.FieldByName("Handle" + h)
		if !ok {
			return fmt.Errorf("handle %s: %s has no handler", h, d.name)
		}
		req, err := g.typeExpr(f.Type.In(1))
		if err != nil {
			return err
		}
		resp, err := g.typeExpr(f.Type.Out(0))
		if err != nil {
			return err
		}
		var cmds []*rowfile.Command
		for _, i := range byName[h] {
			cmds = append(cmds, &c.Commands[i])
		}
		fn, err := fieldsFn(d, cmds, "req")
		if err != nil {
			return err
		}
		g.useStd("context")
		var whens []*rowfile.When
		for _, c := range cmds {
			whens = append(whens, c.When)
		}
		guard := ""
		if !slices.Contains(whens, nil) {
			var conds []string
			for _, wn := range whens {
				conds = append(conds, "b.match("+whenp(wn)+")")
			}
			guard = strings.Join(conds, " || ")
			fmt.Fprintf(w, "if %s {\n", guard)
		}
		otherwise, err := g.otherwise(f.Type.Out(0), cmds)
		if err != nil {
			return fmt.Errorf("handle %s: %w", h, err)
		}
		fmt.Fprintf(w, "d.Handle%s = func(_ context.Context, req %s) (resp %s, err error) {\nf := %s\n", h, req, resp, fn)
		if otherwise != "" {
			w.WriteString("handled := false\n")
		}
		for _, i := range byName[h] {
			cond, err := g.cond(d, &c.Commands[i], "req")
			if err != nil {
				return err
			}
			mark := ""
			if otherwise != "" {
				mark = "\nhandled = true"
			}
			fmt.Fprintf(w, "if %s {\nb.emit(ci, %d, f)%s\n}\n", cond, i, mark)
		}
		if otherwise != "" {
			fmt.Fprintf(w, "if !handled {\nresp = %s\n}\n", otherwise)
		}
		w.WriteString("return resp, err\n}\n")
		if guard != "" {
			w.WriteString("}\n")
		}
	}
	return nil
}

// otherwise is the response literal of a handler's commands' otherwise
// ("" for none); the commands of one handler state at most one.
func (g *gen) otherwise(resp reflect.Type, cmds []*rowfile.Command) (string, error) {
	var lit map[string]any
	for _, c := range cmds {
		if c.Otherwise == nil {
			continue
		}
		if lit != nil {
			return "", errors.New("otherwise twice")
		}
		lit = c.Otherwise
	}
	if lit == nil {
		return "", nil
	}
	if resp.Kind() != reflect.Struct || resp.NumField() == 0 {
		return "", fmt.Errorf("otherwise: the response %s has no fields", resp)
	}
	return g.literal(resp, lit)
}

func (g *gen) onWrite(w *bytes.Buffer, c *rowfile.Cluster, d def) error {
	var cmds []*rowfile.Command
	var idx []int
	for i := range c.Commands {
		if len(c.Commands[i].Write) > 0 {
			cmds = append(cmds, &c.Commands[i])
			idx = append(idx, i)
		}
	}
	if len(cmds) == 0 {
		return nil
	}
	if _, ok := d.declare.FieldByName("OnWrite"); !ok {
		return fmt.Errorf("write: %s takes no write veto", d.name)
	}
	fn, err := fieldsFn(d, cmds, "next")
	if err != nil {
		return err
	}
	g.useStd("context")
	fmt.Fprintf(w, "d.OnWrite = func(_ context.Context, next %s.State, attrID uint32) error {\nf := %s\n", d.alias, fn)
	for j, cmd := range cmds {
		var ids []string
		for _, a := range cmd.Write {
			if _, _, _, err := field(d, a); err != nil {
				return err
			}
			ids = append(ids, d.alias+".Attr"+a)
		}
		cond, err := g.cond(d, cmd, "next")
		if err != nil {
			return err
		}
		g.useStd("slices")
		fmt.Fprintf(w, "if slices.Contains([]uint32{%s}, attrID) && %s {\nb.emit(ci, %d, f)\n}\n", strings.Join(ids, ", "), cond, idx[j])
	}
	w.WriteString("return nil\n}\n")
	return nil
}

func (g *gen) apply(w *bytes.Buffer, c *rowfile.Cluster, d def) error {
	var body bytes.Buffer
	for i := range c.Attributes {
		if err := g.assign(&body, d, &c.Attributes[i], "p", "&st", "ci", i, true); err != nil {
			return err
		}
	}
	if c.Options != nil {
		fmt.Fprintf(&body, "n += b.options%sApply(&p, &st, ci)\n", materializers[d.name])
	}
	fmt.Fprintf(w, "apply: func(b *binding, ci int, st model.State) (any, error) {\nvar p %s.Patch\nn := 0\n%sif n == 0 {\nreturn nil, nil\n}\nreturn p, %s.Wrap(b.server(%s.ClusterID)).Set(p)\n},\n",
		d.alias, body.String(), d.alias, d.alias)
	return nil
}

func (g *gen) watch(w *bytes.Buffer, c *rowfile.Cluster, d def) error {
	var cmds []*rowfile.Command
	var idx []int
	for i := range c.Commands {
		if len(c.Commands[i].Change) > 0 {
			cmds = append(cmds, &c.Commands[i])
			idx = append(idx, i)
		}
	}
	fn, err := fieldsFn(d, cmds, "st")
	if err != nil {
		return err
	}
	g.contract = true
	var body bytes.Buffer
	for j, cmd := range cmds {
		var ids []string
		for _, a := range cmd.Change {
			if _, _, _, err := field(d, a); err != nil {
				return err
			}
			ids = append(ids, d.alias+".Attr"+a)
		}
		cond, err := g.cond(d, cmd, "st")
		if err != nil {
			return err
		}
		for _, a := range cmd.Unless {
			if _, _, _, err := field(d, a); err != nil {
				return err
			}
			cond += " && !slices.Contains(c.Attributes, " + d.alias + ".Attr" + a + ")"
			g.useStd("slices")
		}
		fmt.Fprintf(&body, "if changed(c, %s) && %s {\nb.emit(ci, %d, f)\n}\n", strings.Join(ids, ", "), cond, idx[j])
	}
	get := ""
	if strings.Contains(fn, "st.") || strings.Contains(body.String(), "st.") {
		get = fmt.Sprintf("st := %s.Wrap(b.server(%s.ClusterID)).Get()\n", d.alias, d.alias)
	}
	fmt.Fprintf(w, "watch: func(b *binding, ci int) func() {\nreturn b.target.OnChanged(%s.ClusterID, func(c contract.Change) {\n%sf := %s\n%s})\n},\n",
		d.alias, get, fn, body.String())
	return nil
}

// materializers are the clusters whose options a Go materializer of the
// root package turns into attributes and a command handler (options.go:
// b.options<Name> fills the declaration, b.options<Name>Apply the patch
// of a state).
var materializers = map[string]string{
	"ModeSelect": "ModeSelect",
}

// portMaterializers are the clusters a row may mark `ports: host`: a Go
// materializer of the root package (ports.go: b.ports<Name>) sets the
// declaration's port fields from the consumer's host object
// (Options.Ports) and reports false when the host lacks one the
// cluster needs; the row then does not apply to the entity.
var portMaterializers = map[string]string{
	"WebRtcTransportProvider":  "WebRTCProvider",
	"CameraAvStreamManagement": "AvStream",
}

// Commands lists the command kinds a row may use, for the docs.
var Commands = []string{"handle", "write", "change"}
