// Package gen generates rows_gen.go, the Go form of the table, from
// rows/*.yaml (internal/rowfile). Every name a row uses — the device
// type, the cluster, its features, attributes, commands and enum
// constants — is checked against go-fabric's generated device and
// <cluster>def packages, and the emitted code is typed by them, so a row
// that names something go-fabric does not have fails here or in the
// compile. The command is internal/gen/cmd; the staleness test of the
// root package compares its output with the committed file.
package gen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"reflect"
	"slices"
	"strconv"
	"strings"

	"github.com/SukramJ/go-fabric/device"

	"github.com/SukramJ/go-hamapping/internal/rowfile"
)

// Output is the file the generator writes, relative to the module root.
const Output = "rows_gen.go"

// Docs is the page whose row table the generator writes, between
// TableBegin and TableEnd.
const (
	Docs       = "docs/rows.md"
	TableBegin = "<!-- rows:begin (generated by internal/gen; do not edit) -->"
	TableEnd   = "<!-- rows:end -->"
)

// Table returns the markdown table of every row of files.
func Table(files []rowfile.File) string {
	var b strings.Builder
	b.WriteString("| Row | Predicate | Device type | Clusters | Verdict | Cites |\n| --- | --- | --- | --- | --- | --- |\n")
	cell := func(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ") }
	for _, f := range files {
		for i := range f.Rows {
			r := &f.Rows[i]
			var cs []string
			for j := range r.Clusters {
				c := &r.Clusters[j]
				name := c.Cluster
				var fs []string
				for _, ft := range c.Features {
					fs = append(fs, ft.Name)
				}
				if len(fs) > 0 {
					name += " (" + strings.Join(fs, ", ") + ")"
				}
				for _, e := range c.Events {
					var es []string
					for _, x := range e.Emit {
						es = append(es, x.Event)
					}
					name += " [on " + e.On + ": " + strings.Join(es, ", ") + "]"
				}
				if o := c.Options; o != nil {
					name += " [options " + o.List + " at " + o.Current + " to " + o.Method + "]"
				}
				if c.Ports != "" {
					name += " [ports: " + c.Ports + "]"
				}
				cs = append(cs, name)
			}
			for _, p := range r.Parts {
				cs = append(cs, "part "+p.Type)
			}
			if r.RideMeasurement != nil {
				cs = append(cs, "rides as the "+r.RideMeasurement.Class+" measurement")
			}
			typ := r.Type
			if r.Ride != "" && typ != "" {
				typ += " (rides on the primary)"
			}
			fmt.Fprintf(&b, "| `%s/%s` | %s | %s | %s | %s | %s |\n", f.Platform, r.ID, cell(describeWhen(&r.When)), cell(typ),
				cell(strings.Join(cs, "; ")), cell(r.Verdict), cell(strings.Join(r.Cites, "; ")))
		}
	}
	return b.String()
}

func describeWhen(w *rowfile.When) string {
	var parts []string
	if w.DeviceClass != nil {
		parts = append(parts, "device_class "+strings.Join(w.DeviceClass, ", "))
	}
	if w.Unit != nil {
		parts = append(parts, "unit "+strings.Join(w.Unit, ", "))
	}
	if w.StateClass != nil {
		parts = append(parts, "state_class "+strings.Join(w.StateClass, ", "))
	}
	if w.Features != nil {
		parts = append(parts, "features "+describeSet(w.Features))
	}
	for _, k := range slices.Sorted(mapKeys(w.Extra)) {
		s := w.Extra[k]
		parts = append(parts, k+" "+describeSet(&s))
	}
	if len(parts) == 0 {
		return "any"
	}
	return strings.Join(parts, "; ")
}

func describeSet(s *rowfile.Set) string {
	var parts []string
	if s.All != nil {
		parts = append(parts, "all of "+strings.Join(s.All, ", "))
	}
	if s.Any != nil {
		parts = append(parts, "any of "+strings.Join(s.Any, ", "))
	}
	if s.None != nil {
		parts = append(parts, "none of "+strings.Join(s.None, ", "))
	}
	if s.Present != nil {
		parts = append(parts, fmt.Sprintf("present %v", *s.Present))
	}
	if s.True != nil {
		parts = append(parts, fmt.Sprintf("is %v", *s.True))
	}
	return strings.Join(parts, ", ")
}

// Splice returns page with its row table replaced by table.
func Splice(page []byte, table string) ([]byte, error) {
	return SpliceBetween(page, TableBegin, TableEnd, table)
}

// SpliceBetween returns page with the text between begin and end
// replaced by table.
func SpliceBetween(page []byte, begin, end, table string) ([]byte, error) {
	s := string(page)
	i, j := strings.Index(s, begin), strings.Index(s, end)
	if i < 0 || j < i {
		return nil, fmt.Errorf("gen: %s has no %q ... %q", Docs, begin, end)
	}
	return []byte(s[:i+len(begin)] + "\n\n" + table + "\n" + s[j:]), nil
}

// Page returns the page with both generated tables (the rows and the
// keys a source fills) replaced from files.
func Page(page []byte, files []rowfile.File) ([]byte, error) {
	page, err := Splice(page, Table(files))
	if err != nil {
		return nil, err
	}
	return SpliceBetween(page, KeysBegin, KeysEnd, KeysTable(files))
}

// Generate returns rows_gen.go for the row files of dir.
func Generate(dir string) ([]byte, error) {
	files, err := rowfile.Load(dir)
	if err != nil {
		return nil, err
	}
	return GenerateFiles(files)
}

// GenerateFiles returns rows_gen.go for files.
func GenerateFiles(files []rowfile.File) ([]byte, error) {
	g := &gen{imports: map[string]string{}}
	var body bytes.Buffer
	body.WriteString("var rows = []Row{\n")
	for _, f := range files {
		for i := range f.Rows {
			if err := g.row(&body, &f, &f.Rows[i]); err != nil {
				return nil, fmt.Errorf("%s: row %s: %w", f.Name, f.Rows[i].ID, err)
			}
		}
	}
	body.WriteString("}\n")
	var out bytes.Buffer
	out.WriteString("// SPDX-License-Identifier: Apache-2.0\n// Copyright (C) 2026 SukramJ.\n\n")
	out.WriteString("// Code generated by internal/gen from rows/*.yaml. DO NOT EDIT.\n\npackage hamapping\n\nimport (\n")
	paths := []string{"github.com/SukramJ/go-fabric/eligibility"}
	if g.std["context"] {
		out.WriteString("\t\"context\"\n")
	}
	if g.std["slices"] {
		out.WriteString("\t\"slices\"\n")
	}
	out.WriteString("\n")
	if g.contract {
		paths = append(paths, "github.com/SukramJ/go-fabric/contract")
	}
	paths = append(paths, "github.com/SukramJ/go-fabric/device")
	for p := range g.imports {
		paths = append(paths, p)
	}
	paths = append(paths, "github.com/SukramJ/go-hamqtt/model")
	slices.Sort(paths)
	for _, p := range paths {
		if a, ok := g.imports[p]; ok {
			fmt.Fprintf(&out, "\t%s %q\n", a, p)
			continue
		}
		fmt.Fprintf(&out, "\t%q\n", p)
	}
	out.WriteString(")\n\n")
	out.WriteString(methodsSource(files))
	out.WriteString("// rows is the table, in the order [Map] tries it.\n")
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gen: format: %w\n%s", err, out.Bytes())
	}
	return src, nil
}

type gen struct {
	imports  map[string]string
	std      map[string]bool
	contract bool
}

func (g *gen) use(d def) string {
	g.imports[d.path] = d.alias
	return d.alias
}

func (g *gen) useStd(p string) {
	if g.std == nil {
		g.std = map[string]bool{}
	}
	g.std[p] = true
}

// deviceType returns the go-fabric device type named name.
func deviceType(name string) (*device.Type, bool) {
	for _, t := range device.Types() {
		if t.Name == name {
			return t, true
		}
	}
	return nil, false
}

// allowed reports whether a device type may carry the cluster: its own
// server list, or PowerSource, which BridgedNode lists under the condition
// BridgedPowerSourceInfo for every bridged device.
func allowed(t *device.Type, id uint32) bool {
	if _, ok := t.Server(id); ok {
		return true
	}
	r, ok := device.BridgedNodeType.Server(id)
	return ok && r.Conformance == device.ConditionBridgedPowerSourceInfo
}

func (g *gen) row(w *bytes.Buffer, f *rowfile.File, r *rowfile.Row) error {
	state, reason, err := rowfile.ParseVerdict(r.Verdict)
	if err != nil {
		return err
	}
	fmt.Fprintf(w, "{\nID: %q, Platform: %q,\n", f.Platform+"/"+r.ID, f.Platform)
	fmt.Fprintf(w, "When: %s,\n", when(&r.When))
	switch state {
	case rowfile.Mappable:
		w.WriteString("State: eligibility.StateMappable,\n")
	case rowfile.Partial:
		w.WriteString("State: eligibility.StatePartial,\n")
	default:
		w.WriteString("State: eligibility.StateUnmappable,\n")
	}
	if reason != "" {
		fmt.Fprintf(w, "Reason: %q,\n", reason)
	}
	cites := slices.Concat(r.Cites, f.Cites)
	if len(cites) > 0 {
		fmt.Fprintf(w, "Cites: %s,\n", strs(cites))
	}
	if state == rowfile.Unmappable {
		w.WriteString("},\n")
		return nil
	}
	t, ok := deviceType(r.Type)
	if !ok {
		return fmt.Errorf("device type %q: go-fabric's device package has none", r.Type)
	}
	fmt.Fprintf(w, "Type: &device.%sType,\n", t.Name)
	if r.Ride != "" {
		fmt.Fprintf(w, "Ride: %q,\n", r.Ride)
	}
	if len(r.Caveats) > 0 {
		w.WriteString("Caveats: []Caveat{\n")
		for i := range r.Caveats {
			fmt.Fprintf(w, "{When: %s, Reason: %q},\n", when(&r.Caveats[i].When), r.Caveats[i].Reason)
		}
		w.WriteString("},\n")
	}
	if m := r.RideMeasurement; m != nil {
		g.contract = true
		fmt.Fprintf(w, "RideMeasurement: &Measurement{Class: contract.%s, Value: %s},\n", rowfile.MeasurementClasses[m.Class], g.value(&m.Value, nil))
	}
	if err := g.clusters(w, t, r.Clusters); err != nil {
		return err
	}
	if len(r.Parts) > 0 {
		w.WriteString("Parts: []Part{\n")
		for _, p := range r.Parts {
			pt, ok := deviceType(p.Type)
			if !ok {
				return fmt.Errorf("part %q: go-fabric's device package has none", p.Type)
			}
			fmt.Fprintf(w, "{Type: &device.%sType,\n", pt.Name)
			if err := g.clusters(w, pt, p.Clusters); err != nil {
				return fmt.Errorf("part %s: %w", p.Type, err)
			}
			w.WriteString("},\n")
		}
		w.WriteString("},\n")
	}
	w.WriteString("},\n")
	return nil
}

func (g *gen) clusters(w *bytes.Buffer, t *device.Type, cs []rowfile.Cluster) error {
	w.WriteString("Clusters: []Cluster{\n")
	for i := range cs {
		c := &cs[i]
		d, ok := defs[c.Cluster]
		if !ok {
			return fmt.Errorf("cluster %q: no <cluster>def package listed in internal/gen", c.Cluster)
		}
		if !allowed(t, d.id) {
			return fmt.Errorf("cluster %s: device type %s does not list it", c.Cluster, t.Name)
		}
		if err := g.cluster(w, c, d); err != nil {
			return fmt.Errorf("cluster %s: %w", c.Cluster, err)
		}
	}
	w.WriteString("},\n")
	return nil
}

// --- the data half -----------------------------------------------------

func strs(s []string) string {
	q := make([]string, len(s))
	for i, x := range s {
		q[i] = strconv.Quote(x)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func classes(s []string) []string {
	out := make([]string, len(s))
	for i, x := range s {
		if x == "none" {
			x = ""
		}
		out[i] = x
	}
	return out
}

func boolp(b *bool) string {
	if *b {
		return "new(true)"
	}
	return "new(false)"
}

func set(s *rowfile.Set) string {
	var parts []string
	if s.All != nil {
		parts = append(parts, "All: "+strs(s.All))
	}
	if s.Any != nil {
		parts = append(parts, "Any: "+strs(s.Any))
	}
	if s.None != nil {
		parts = append(parts, "None: "+strs(s.None))
	}
	if s.Present != nil {
		parts = append(parts, "Present: "+boolp(s.Present))
	}
	if s.True != nil {
		parts = append(parts, "True: "+boolp(s.True))
	}
	return "Set{" + strings.Join(parts, ", ") + "}"
}

func when(w *rowfile.When) string {
	var parts []string
	if w.DeviceClass != nil {
		parts = append(parts, "DeviceClass: "+strs(classes(w.DeviceClass)))
	}
	if w.Unit != nil {
		parts = append(parts, "Unit: "+strs(w.Unit))
	}
	if w.StateClass != nil {
		parts = append(parts, "StateClass: "+strs(w.StateClass))
	}
	if w.Features != nil {
		parts = append(parts, "Features: &"+set(w.Features))
	}
	if len(w.Extra) > 0 {
		keys := slices.Sorted(mapKeys(w.Extra))
		es := make([]string, 0, len(keys))
		for _, k := range keys {
			s := w.Extra[k]
			es = append(es, fmt.Sprintf("%q: %s", k, set(&s)))
		}
		parts = append(parts, "Extra: map[string]Set{"+strings.Join(es, ", ")+"}")
	}
	if w.Options != nil {
		parts = append(parts, "Options: "+boolp(w.Options))
	}
	return "When{" + strings.Join(parts, ", ") + "}"
}

func whenp(w *rowfile.When) string {
	if w == nil {
		return "nil"
	}
	return "&" + when(w)
}

func mapKeys[V any](m map[string]V) func(func(string) bool) {
	return func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}
}

func float(f float64) string { return strconv.FormatFloat(f, 'g', -1, 64) }

func fptr(f *float64) string {
	if f == nil {
		return "nil"
	}
	return "new(float64(" + float(*f) + "))"
}

func scale(s *float64) float64 {
	if s == nil {
		return 1
	}
	return *s
}

func constLit(v any) string {
	switch t := v.(type) {
	case string:
		return strconv.Quote(t)
	case bool:
		return strconv.FormatBool(t)
	case int:
		return "float64(" + strconv.Itoa(t) + ")"
	case float64:
		return "float64(" + float(t) + ")"
	}
	return "nil"
}

// value is the runtime Value of v; enum is the command direction's
// integer table of the field the value reads.
func (g *gen) value(v *rowfile.Value, enumExpr func(string) string) string {
	var parts []string
	if v.From != "" {
		parts = append(parts, fmt.Sprintf("From: %q", v.From))
	}
	if v.Field != "" {
		parts = append(parts, fmt.Sprintf("Field: %q", v.Field))
	}
	if v.Const != nil {
		parts = append(parts, "Const: "+constLit(v.Const), "HasConst: true")
	}
	if v.Units != nil {
		us := make([]string, 0, len(v.Units))
		for _, u := range slices.Sorted(mapKeys(v.Units)) {
			l := v.Units[u]
			us = append(us, fmt.Sprintf("%q: {Offset: %s, Scale: %s, Add: %s}", u, float(l.Offset), float(scale(l.Scale)), float(l.Add)))
		}
		parts = append(parts, "Units: map[string]Linear{"+strings.Join(us, ", ")+"}")
	}
	if v.DefaultUnit != "" {
		parts = append(parts, fmt.Sprintf("DefaultUnit: %q", v.DefaultUnit))
	}
	off, add := 0.0, 0.0
	if v.Offset != nil {
		off = *v.Offset
	}
	if v.Add != nil {
		add = *v.Add
	}
	if off != 0 || scale(v.Scale) != 1 || add != 0 {
		parts = append(parts, fmt.Sprintf("Linear: Linear{Offset: %s, Scale: %s, Add: %s}", float(off), float(scale(v.Scale)), float(add)))
	}
	if v.Func != "" {
		parts = append(parts, fmt.Sprintf("Func: %q", v.Func))
	}
	if v.Min != nil {
		parts = append(parts, "Min: "+fptr(v.Min))
	}
	if v.Max != nil {
		parts = append(parts, "Max: "+fptr(v.Max))
	}
	if v.Digits != 0 {
		parts = append(parts, fmt.Sprintf("Digits: %d", v.Digits))
	}
	if enumExpr != nil && len(v.Enum) > 0 {
		es := make([]string, 0, len(v.Enum))
		for _, k := range slices.Sorted(mapKeys(v.Enum)) {
			es = append(es, fmt.Sprintf("%s: %q", enumExpr(k), fmt.Sprint(v.Enum[k])))
		}
		parts = append(parts, "Enum: map[int64]string{"+strings.Join(es, ", ")+"}")
	}
	if v.Per != "" {
		parts = append(parts, fmt.Sprintf("Per: %q", v.Per))
	}
	if v.Times != "" {
		parts = append(parts, fmt.Sprintf("Times: %q", v.Times))
	}
	if v.Catalog {
		parts = append(parts, "Catalog: true")
	}
	return "Value{" + strings.Join(parts, ", ") + "}"
}

